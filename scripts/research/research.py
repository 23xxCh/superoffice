import os
import json
import asyncio
from pathlib import Path
from typing import Optional, List, Dict
from dataclasses import dataclass, field
from datetime import datetime
import httpx


@dataclass
class ResearchConfig:
    """Configuration for research"""
    api_key: str = ""
    base_url: str = "https://api.minimax.chat/v1"
    default_model: str = "MiniMax-M2.7"
    max_results_per_search: int = 10


class ResearchPlanner:
    """Research planning and orchestration"""

    def __init__(self, config: Optional[ResearchConfig] = None):
        self.config = config or ResearchConfig()
        self.client = httpx.AsyncClient(timeout=60.0)

    async def create_plan(
        self,
        request: str,
        output_dir: str,
        dimensions: Optional[List[str]] = None
    ) -> Dict:
        """Create research plan from user request"""
        output_path = Path(output_dir)
        output_path.mkdir(parents=True, exist_ok=True)

        # Default dimensions if not specified
        if not dimensions:
            dimensions = ["overview", "technology", "market", "challenges", "future"]

        # Generate plan using LLM
        plan = {
            "request": request,
            "created_at": datetime.now().isoformat(),
            "dimensions": [],
            "status": "planned"
        }

        for dim in dimensions:
            plan["dimensions"].append({
                "name": dim,
                "search_queries": [f"{request} {dim}", f"{dim} {request}"],
                "status": "pending"
            })

        # Save plan
        plan_path = output_path / "plan.json"
        with open(plan_path, "w", encoding="utf-8") as f:
            json.dump(plan, f, ensure_ascii=False, indent=2)

        return {"plan_path": str(plan_path), "dimensions": dimensions}

    async def execute_dimension(
        self,
        dimension: str,
        plan_path: str
    ) -> Dict:
        """Execute research for one dimension"""
        plan_file = Path(plan_path)
        if not plan_file.exists():
            return {"error": "Plan file not found"}

        with open(plan_file, "r", encoding="utf-8") as f:
            plan = json.load(f)

        # Find dimension in plan
        dim_info = None
        for dim in plan["dimensions"]:
            if dim["name"] == dimension:
                dim_info = dim
                break

        if not dim_info:
            return {"error": f"Dimension not found: {dimension}"}

        # Execute searches
        results = []
        for query in dim_info.get("search_queries", []):
            # Simplified - would call actual search functions
            search_result = await self._search_academic(query)
            results.append({"query": query, "results": search_result})

        # Generate dimension report
        report = {
            "dimension": dimension,
            "request": plan["request"],
            "search_results": results,
            "findings": [],  # Would be generated by LLM
            "sources": []    # Would track all sources
        }

        # Save dimension report
        report_path = plan_file.parent / f"dimension_{dimension}.md"
        with open(report_path, "w", encoding="utf-8") as f:
            f.write(f"# Research: {dimension}\n\n")
            f.write(f"**Request**: {plan['request']}\n\n")
            f.write(f"## Search Results\n\n")
            for result in results:
                f.write(f"### {result['query']}\n\n")
                f.write(f"Found {len(result['results'])} results\n\n")

        return {"report_path": str(report_path), "dimension": dimension}

    async def _search_academic(self, query: str, max_results: int = 10) -> List[Dict]:
        """Search academic sources"""
        # Simplified placeholder
        # Would integrate with ArXiv, Semantic Scholar, PubMed APIs
        return [{"title": f"Result for {query}", "source": "academic", "url": ""}]

    async def synthesize(
        self,
        dimension_reports: List[str],
        output_path: str
    ) -> Dict:
        """Synthesize findings from multiple dimensions"""
        findings = []
        consensus = []
        conflicts = []
        uncertainties = []

        # Load all dimension reports
        for report_path in dimension_reports:
            if os.path.exists(report_path):
                with open(report_path, "r", encoding="utf-8") as f:
                    content = f.read()
                    findings.append(content)

        # Generate synthesis
        synthesis = {
            "created_at": datetime.now().isoformat(),
            "dimensions": len(dimension_reports),
            "consensus": consensus,
            "conflicts": conflicts,
            "uncertainties": uncertainties,
            "summary": "Synthesized from " + str(len(dimension_reports)) + " dimensions"
        }

        # Save synthesis
        with open(output_path, "w", encoding="utf-8") as f:
            json.dump(synthesis, f, ensure_ascii=False, indent=2)

        return {"synthesis_path": output_path}

    async def generate_report(
        self,
        synthesis_path: str,
        format: str = "markdown"
    ) -> Dict:
        """Generate final report from synthesis"""
        if not os.path.exists(synthesis_path):
            return {"error": "Synthesis file not found"}

        with open(synthesis_path, "r", encoding="utf-8") as f:
            synthesis = json.load(f)

        # Generate markdown report
        report = f"""# Research Report

**Generated**: {synthesis.get('created_at', '')}

## Summary

{synthesis.get('summary', '')}

## Key Findings

"""

        for item in synthesis.get("consensus", []):
            report += f"- {item}\n"

        report += "\n## Areas of Uncertainty\n\n"
        for item in synthesis.get("uncertainties", []):
            report += f"- {item}\n"

        # Save report
        report_path = synthesis_path.replace("_synthesis.json", "_report.md")
        with open(report_path, "w", encoding="utf-8") as f:
            f.write(report)

        return {"report_path": report_path, "format": format}

    async def close(self):
        await self.client.aclose()


